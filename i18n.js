  var currentLang = "en";

  function applyLang(lang) {
    currentLang = lang;
    var root = document.documentElement;
    root.lang = lang;
    /* Keep LTR layout so margins, spacing, and stacking match English */
    root.dir = "ltr";

    if (I18N[lang]["page.title"]) document.title = I18N[lang]["page.title"];
    var metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc && I18N[lang]["meta.description"]) {
      metaDesc.setAttribute("content", I18N[lang]["meta.description"]);
    }

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (I18N[lang][key] !== undefined) el.textContent = I18N[lang][key];
    });

    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-html");
      if (I18N[lang][key] !== undefined) el.innerHTML = I18N[lang][key];
    });

    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-aria");
      if (I18N[lang][key] !== undefined) el.setAttribute("aria-label", I18N[lang][key]);
    });

    document.querySelectorAll("[data-i18n-wa]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-wa");
      var base = el.getAttribute("data-wa-base");
      if (base && I18N[lang][key] !== undefined) {
        el.setAttribute("href", base + "?text=" + encodeURIComponent(I18N[lang][key]));
      }
    });

    document.querySelectorAll(".lang-toggle").forEach(function (btn) {
      btn.setAttribute("aria-label", lang === "en" ? "Switch to Arabic" : "التبديل إلى الإنجليزية");
    });

    document.documentElement.classList.remove("i18n-pending");
    document.documentElement.classList.add("i18n-ready");

    try {
      localStorage.setItem("lang", lang);
    } catch (e) {}
  }

  function init() {
    var saved;
    try {
      saved = localStorage.getItem("lang");
    } catch (e) {}
    applyLang(saved === "ar" || saved === "en" ? saved : "en");

    document.querySelectorAll(".lang-toggle").forEach(function (btn) {
      btn.addEventListener("click", function () {
        applyLang(currentLang === "en" ? "ar" : "en");
      });
    });
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
